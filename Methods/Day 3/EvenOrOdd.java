
public class EvenOrOdd {

    static void isEvenOrOdd(int n){
        if(n%2==0){
            System.out.println("The Number is Even : "+n);
        }else{
             System.out.println("The Number is odd : "+n);
        }

    }
    public static void main(String args[]){
        int n  = 19;
        isEvenOrOdd(n);
        
    }
}
